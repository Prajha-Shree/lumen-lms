import { randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, rename, rm, stat } from 'node:fs/promises';
import path from 'node:path';
import type { Readable } from 'node:stream';
import { env } from '../config/env.js';

/**
 * Storage driver for uploaded files. Keys are opaque and tenant-prefixed. The local
 * driver is for development and single-node deployments; an S3 / Azure Blob driver
 * implements the same interface for cloud.
 */
export interface FileStorage {
  /** Moves a temp file (from multer) into permanent storage and returns its key. */
  put(tenantId: string, tempPath: string, originalName: string): Promise<string>;
  read(key: string): Readable;
  remove(key: string): Promise<void>;
}

class LocalDiskStorage implements FileStorage {
  constructor(private readonly root: string) {}

  private resolve(key: string) {
    const full = path.resolve(this.root, key);
    // Keys are generated by us, but never let one escape the storage root.
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error('Invalid storage key');
    return full;
  }

  async put(tenantId: string, tempPath: string, originalName: string) {
    const ext = path.extname(originalName).toLowerCase().replace(/[^.a-z0-9]/g, '').slice(0, 10);
    const key = `${tenantId}/${randomUUID()}${ext}`;
    const dest = this.resolve(key);
    await mkdir(path.dirname(dest), { recursive: true });
    await rename(tempPath, dest);
    return key;
  }

  read(key: string) {
    return createReadStream(this.resolve(key));
  }

  async remove(key: string) {
    await rm(this.resolve(key), { force: true });
  }

  async exists(key: string) {
    return stat(this.resolve(key)).then(
      () => true,
      () => false,
    );
  }
}

export const storage: FileStorage = new LocalDiskStorage(env.UPLOAD_DIR);
export const TEMP_UPLOAD_DIR = path.join(env.UPLOAD_DIR, '.tmp');
